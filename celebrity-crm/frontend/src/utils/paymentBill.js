import { jsPDF } from "jspdf";

const rupees = (value) => `Rs. ${Number(value).toLocaleString("en-IN")}`;

const day = (date) =>
  date.toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });

export const billNumber = (payment) =>
  `BILL-${String(payment.id).padStart(5, "0")}`;

export function downloadBill(payment, name) {
  const received = payment.receivedAmount || payment.amount;
  const balance = payment.amount - received;
  const doc = new jsPDF({ unit: "mm", format: "a4" });

  doc.setFillColor(20, 18, 28);
  doc.rect(0, 0, 210, 40, "F");
  doc.setTextColor(232, 190, 90);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.text("PAYMENT BILL", 15, 24);
  doc.setFontSize(10);
  doc.setTextColor(255, 255, 255);
  doc.text(billNumber(payment), 195, 18, { align: "right" });
  doc.text(day(payment.date), 195, 25, { align: "right" });

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120, 120, 120);
  doc.text("RECEIVED FROM", 15, 56);
  doc.text("PAID TO", 115, 56);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(30, 30, 30);
  doc.text(payment.payer, 15, 64);
  doc.text(name, 115, 64);

  doc.setDrawColor(210, 210, 210);
  doc.line(15, 78, 195, 78);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120, 120, 120);
  doc.text("DESCRIPTION", 15, 85);
  doc.text("AMOUNT", 195, 85, { align: "right" });
  doc.line(15, 89, 195, 89);

  doc.setFontSize(12);
  doc.setTextColor(30, 30, 30);
  doc.text(payment.project, 15, 98);
  doc.text(rupees(payment.amount), 195, 98, { align: "right" });
  doc.setFontSize(10);
  doc.setTextColor(120, 120, 120);
  doc.text(`${payment.kind} - ${payment.projectType}`, 15, 105);
  doc.line(15, 112, 195, 112);

  let y = 124;
  const total = (label, value, bold) => {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setFontSize(bold ? 13 : 11);
    doc.setTextColor(30, 30, 30);
    doc.text(label, 115, y);
    doc.text(value, 195, y, { align: "right" });
    y += 9;
  };
  total("Bill amount", rupees(payment.amount), false);
  total("Received", rupees(received), true);
  total("Balance", rupees(balance), false);

  y += 6;
  doc.line(15, y, 195, y);
  y += 10;
  const detail = (label, value) => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(120, 120, 120);
    doc.text(label, 15, y);
    doc.setFontSize(11);
    doc.setTextColor(30, 30, 30);
    const lines = doc.splitTextToSize(value || "-", 135);
    doc.text(lines, 60, y);
    y += 8 * lines.length;
  };
  detail("STATUS", balance === 0 ? "Paid in full" : "Partly paid");
  detail("METHOD", payment.method);
  detail("REFERENCE", payment.reference);
  detail("NOTE", payment.note);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(150, 150, 150);
  doc.text("This bill was generated by Celebrity CRM.", 105, 285, {
    align: "center",
  });

  doc.save(`${billNumber(payment)}.pdf`);
}